"""Summarise scripts/repeated_cv.sh into OUT/REPEATED_CV.md and OUT/repeated_cv_diffs.csv.

Input: OUT/seed_<s>/artifacts/results_raw.csv (run, dataset, fold, N, metric, value) per seed.

    Check        seed 42 is the main experiment's split: its fold-tree sha256 and every metric
                 must equal paper_artifacts/ (config.json, results_raw.csv)
    Methods      mean ± std of A, B, C. "std over folds" = sample std of the 50 fold values
                 (5 seeds x 10 folds); "std over seeds" = sample std of the 5 seed means, i.e.
                 how much a method's reported mean moves when the corpus is split differently
    Differences  per seed, the paired fold differences KG run - A: mean, sample std, 95% CI
                 (t, 9 df), two-sided Wilcoxon signed-rank p over the 10 folds (zero differences
                 dropped; undefined when all are zero), and the folds below / equal / above A.
                 Across seeds: mean and std of the 5 seed means, and their range

The 50 fold differences are not 50 independent samples (each repository is a test case once per
seed, so the seeds re-use the same data); no test is run on them pooled.

Usage: python scripts/summarize_repeated_cv.py OUT
"""

import csv
import json
import statistics
import sys
import warnings
from pathlib import Path

from scipy.stats import t, wilcoxon

warnings.filterwarnings("ignore", module="scipy")

OUT = Path(sys.argv[1])
DS = "readme_8k_desc20"
NS = (5, 10)
METRICS = (("success_rate", "SR"), ("precision", "P"), ("recall", "R"))
NAMES = {"A": "A: KG off", "B": "B: KG append", "C": "C: KG rerank"}

seeds = sorted(int(p.name.split("_")[1]) for p in OUT.glob("seed_*")
               if (p / "artifacts" / "results_raw.csv").exists())


def load(path):
    out = {}
    for r in csv.DictReader(open(path)):
        if r["dataset"] == DS:
            out[(r["run"], r["metric"], int(r["N"]), int(r["fold"]))] = float(r["value"])
    return out


raw = {s: load(OUT / f"seed_{s}" / "artifacts" / "results_raw.csv") for s in seeds}


def folds(s, run, m, n):
    return [raw[s][(run, m, n, k)] for k in range(1, 11)]


def fmt(xs):
    return f"{statistics.mean(xs):.4f} ± {statistics.stdev(xs):.4f}"


lines = ["# Repeated ten-fold cross-validation: is the KG effect noise?", "",
         "Generated by `scripts/summarize_repeated_cv.py` from `scripts/repeated_cv.sh`; "
         "do not edit by hand.", "",
         f"- seeds: {', '.join(map(str, seeds))} (42 = the main experiment's split); "
         f"commit `{(OUT / 'git_sha.txt').read_text().strip()[:7]}`",
         f"- corpus: 644 repositories, CNBN corpus {DS}, KG settings as `scripts/run_experiment.sh`",
         "- every seed: 10 folds; each repository is a test case exactly once per seed", ""]

# Check seed 42 against the main experiment.
if 42 in raw:
    main = load("paper_artifacts/results_raw.csv")
    shared = [k for k in main if k in raw[42]]
    worst = max(abs(main[k] - raw[42][k]) for k in shared) if shared else float("nan")
    mtree = json.load(open("paper_artifacts/config.json"))["datasets"][DS]["fold_tree_sha256"]
    stree = json.load(open(OUT / "seed_42" / "artifacts" / "config.json"))["datasets"][DS]["fold_tree_sha256"]
    lines += ["## Check: seed 42 reproduces the main experiment", "",
              f"- CNBN fold tree sha256: {'identical' if mtree == stree else 'DIFFERENT'} "
              f"(`{stree[:12]}…`)",
              f"- {len(shared):,} fold-level metric values compared with "
              f"`paper_artifacts/results_raw.csv`: largest absolute difference {worst:.2e}", ""]

lines += ["## Each method: mean ± std", "",
          "Over folds = the 50 fold values (5 seeds × 10 folds). Over seeds = the 5 seed means: "
          "how far a method's reported mean moves when the corpus is split differently.", "",
          "| metric | " + " | ".join(f"{NAMES[r]}, over folds | {NAMES[r]}, over seeds" for r in "ABC") + " |",
          "|---|" + "---|" * 6]
for m, short in METRICS:
    for n in NS:
        cells = []
        for r in "ABC":
            allf = [v for s in seeds for v in folds(s, r, m, n)]
            means = [statistics.mean(folds(s, r, m, n)) for s in seeds]
            cells += [fmt(allf), fmt(means)]
        lines.append(f"| {short}@{n} | " + " | ".join(cells) + " |")
lines.append("")

rows_csv = []
for kg in "BC":
    lines += [f"## Paired difference {NAMES[kg]} − A", "",
              "| metric | seed | mean Δ | std of Δ over folds | 95% CI | Wilcoxon p | folds below / equal / above A |",
              "|---|---|---|---|---|---|---|"]
    summary = []
    for m, short in METRICS:
        for n in NS:
            seed_means = []
            diffs = {s: [0.0 if abs(x - y) < 1e-12 else x - y
                         for x, y in zip(folds(s, kg, m, n), folds(s, "A", m, n))] for s in seeds}
            if not any(any(d) for d in diffs.values()):
                # Identical in every fold of every seed: one row says it, not one per seed.
                lines.append(f"| {short}@{n} | all {len(seeds)} | 0 | 0 | — | undefined (all 0) | "
                             f"0 / 10 / 0 in every seed |")
                rows_csv += [[f"{kg}-A", m, n, s, 0.0, 0.0, 0.0, 0.0, "undefined", 0, 10] for s in seeds]
                summary.append((short, n, [0.0] * len(seeds)))
                continue
            for s in seeds:
                d = diffs[s]
                mu, sd = statistics.mean(d), statistics.stdev(d)
                h = t.ppf(0.975, len(d) - 1) * sd / len(d) ** 0.5
                p = (f"{wilcoxon(d, zero_method='wilcox').pvalue:.3g}" if any(d)
                     else "undefined (all 0)")
                below, equal = sum(x < 0 for x in d), sum(x == 0 for x in d)
                lines.append(f"| {short}@{n} | {s} | {mu:+.4f} | {sd:.4f} | "
                             f"[{mu - h:+.4f}, {mu + h:+.4f}] | {p} | {below} / {equal} / {10 - below - equal} |")
                rows_csv.append([f"{kg}-A", m, n, s, mu, sd, mu - h, mu + h, p, below, equal])
                seed_means.append(mu)
            summary.append((short, n, seed_means))
    lines += ["", f"Across the {len(seeds)} seeds:", "",
              "| metric | mean of the seed means | std over seeds | range |", "|---|---|---|---|"]
    for short, n, sm in summary:
        lines.append(f"| {short}@{n} | {statistics.mean(sm):+.4f} | {statistics.stdev(sm):.4f} | "
                     f"[{min(sm):+.4f}, {max(sm):+.4f}] |")
    lines.append("")

with open(OUT / "repeated_cv_diffs.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["comparison", "metric", "N", "seed", "mean_diff", "sd_diff", "ci95_low", "ci95_high",
                "wilcoxon_p", "folds_below", "folds_equal"])
    w.writerows(rows_csv)
(OUT / "REPEATED_CV.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))
