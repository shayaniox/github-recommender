"""Compare CF-only (TopFilter half mode) with the hybrid (CNBN seeds -> CF) on the same repositories.

For each pair LABEL CF_DIR HYBRID_DIR, the two runs must have scored the same test repositories in
every fold (checked). Every metric is recomputed per test repository from the raw
Round<k>/Recommendations and Round<k>/GroundTruth files:

    CF-only           CF list, scored against CF ground truth = the held-back second half of
                      the repository's topics (the first half was CF's input)
    hybrid, matched   hybrid list with the CF-visible first half removed (those topics are
                      known in the CF-only setting and are not credited), scored against the
                      same held-back half
    hybrid, own       hybrid list scored against its own ground truth = all of the repository's
                      topics (the protocol paper_artifacts/REPORT.md uses)

In every case a list is de-duplicated in order first (the hybrid list starts with the 5 CNBN
seeds), precision@N = hits in the top N / N and recall@N = hits / |ground truth|, as the
validator does. The recomputed fold means of "CF-only" and "hybrid, own" are checked against
the validator's SR_/PRC_ and SRB_/PRCB_ files, and the number of mismatches is reported.

Paired tests on (hybrid matched - CF-only): Wilcoxon signed-rank over the ten fold means (as
scripts/collect_results.py) and over the per-repository values; two-sided, zero differences
dropped. The hybrid runs compared are KG-off (run A), matching CF-only, which has KG off.

Usage: python scripts/compare_cf_hybrid.py --out FILE.md \
           --pair 644 outpath/cfonly_644_run/topfilter outpath/experiments/readme_8k_desc20/A \
           --pair 10k outpath/cfonly_10k/topfilter outpath/hybrid_10k/experiments/readme_8k_desc20/A
"""

import argparse
import math
import statistics
import warnings
from pathlib import Path

from scipy.stats import wilcoxon

# Ties or zero differences make scipy fall back from the exact test to the normal approximation.
warnings.filterwarnings("ignore", module="scipy")

ap = argparse.ArgumentParser()
ap.add_argument("--out", required=True)
ap.add_argument("--pair", nargs=3, action="append", required=True,
                metavar=("LABEL", "CF_DIR", "HYBRID_DIR"))
a = ap.parse_args()

NS = (1, 5, 10, 20)
METRICS = ("SR", "P", "R", "nDCG")
FOLDS = range(1, 11)


def topics(path, col):
    out = []
    for line in Path(path).read_text().splitlines():
        v = line.split("\t")
        if len(v) > col and v[col].strip():
            out.append(v[col].strip())
    return out


def dedup(xs, drop=()):
    seen, out = set(drop), []
    for x in xs:
        if x not in seen:
            seen.add(x)
            out.append(x)
    return out


def score(rec, gt):
    """metric -> N -> value for one repository."""
    gt = set(gt)
    out = {m: {} for m in METRICS}
    for n in NS:
        top = rec[:n]
        hits = sum(1 for x in top if x in gt)
        out["SR"][n] = 1.0 if hits else 0.0
        out["P"][n] = hits / n
        out["R"][n] = hits / len(gt) if gt else 0.0
        dcg = sum(1 / math.log2(i + 1) for i, x in enumerate(top, 1) if x in gt)
        idcg = sum(1 / math.log2(i + 1) for i in range(1, min(len(gt), n) + 1))
        out["nDCG"][n] = dcg / idcg if idcg else 0.0
    return out


def validator_rows(path):
    out = {}
    for line in Path(path).read_text().splitlines():
        v = line.split("\t")
        out[int(v[0])] = [float(x) for x in v[1:]]
    return out


def wil(diffs):
    d = [0.0 if abs(x) < 1e-12 else x for x in diffs]
    if not any(d):
        return "undefined (all zero)"
    return f"{wilcoxon(d, zero_method='wilcox').pvalue:.2g}"


def fmt(xs):
    return f"{statistics.mean(xs):.4f} ({statistics.stdev(xs):.4f})"


lines = ["# CF-only versus hybrid", "",
         "Generated by `scripts/compare_cf_hybrid.py` from the runs' raw recommendation and "
         "ground-truth files; do not edit by hand.", "",
         "Same test repositories and folds in both methods of each pair (checked). Hybrid = run A "
         "(readme_8k_desc20 CNBN seeds, KG off); CF-only = TopFilter half mode, KG off.", "",
         "| view | input the method sees | scored against |",
         "|---|---|---|",
         "| CF-only | first half of the repo's own topics | the held-back second half |",
         "| hybrid, matched | README (via 5 CNBN seeds); the first half is removed from its list | "
         "the same held-back second half |",
         "| hybrid, own | README (via 5 CNBN seeds) | all of the repo's topics |", "",
         "The matched view puts both methods on the same target, but not the same information: "
         "CF-only is given half of the owner's topics, the hybrid none (the cold-start case it "
         "exists for). Values are the mean over the ten folds of the fold means, std in "
         "brackets. Δ = hybrid matched − CF-only.", ""]
headline = []
example_done = False

for label, cf_dir, hy_dir in a.pair:
    cf, hy = Path(cf_dir), Path(hy_dir)
    fold = {v: {m: {n: [] for n in NS} for m in METRICS} for v in ("cf", "hm", "ho")}
    repo_vals = {m: {n: [] for n in NS} for m in METRICS}  # per-repo (hm - cf)
    mismatches, checked, n_repos = 0, 0, 0
    for k in FOLDS:
        repos = sorted(p.name for p in (cf / f"Round{k}" / "GroundTruth").iterdir())
        hrepos = sorted(p.name for p in (hy / f"Round{k}" / "GroundTruth").iterdir())
        if repos != hrepos:
            raise SystemExit(f"{label} fold {k}: the two runs scored different repositories")
        n_repos += len(repos)
        per = {v: {m: {n: [] for n in NS} for m in METRICS} for v in ("cf", "hm", "ho")}
        for r in repos:
            gt_half = topics(cf / f"Round{k}" / "GroundTruth" / r, 1)
            gt_all = topics(hy / f"Round{k}" / "GroundTruth" / r, 1)
            visible = [t for t in gt_all if t not in set(gt_half)]
            cf_rec = dedup(topics(cf / f"Round{k}" / "Recommendations" / r, 0))
            hy_rec = dedup(topics(hy / f"Round{k}" / "Recommendations" / r, 0))
            hm_rec = dedup(hy_rec, drop=visible)
            s = {"cf": score(cf_rec, gt_half), "hm": score(hm_rec, gt_half),
                 "ho": score(hy_rec, gt_all)}
            for v in s:
                for m in METRICS:
                    for n in NS:
                        per[v][m][n].append(s[v][m][n])
            for m in METRICS:
                for n in NS:
                    repo_vals[m][n].append(s["hm"][m][n] - s["cf"][m][n])
            if not example_done and len(gt_half) >= 2:
                example_done = True
                ex = (label, k, r, visible, gt_half, cf_rec[:10], hy_rec[:10], hm_rec[:10], s)
        for v in per:
            for m in METRICS:
                for n in NS:
                    fold[v][m][n].append(statistics.mean(per[v][m][n]))
        # The validator's own fold means, for the recomputation check.
        for v, srf, prf in (("cf", f"SR_Round{k}", f"PRC_Round{k}"),
                            ("ho", f"SRB_Round{k}", f"PRCB_Round{k}")):
            d = cf if v == "cf" else hy
            sr, pr = validator_rows(d / "Results" / srf), validator_rows(d / "Results" / prf)
            for n in NS:
                for mine, theirs in ((fold[v]["SR"][n][-1], sr[n][0]),
                                     (fold[v]["R"][n][-1], pr[n][0]),
                                     (fold[v]["P"][n][-1], pr[n][1])):
                    checked += 1
                    mismatches += abs(mine - theirs) > 1e-9

    lines += [f"## {label}", "",
              f"- CF-only: `{cf_dir}`", f"- hybrid: `{hy_dir}`",
              f"- {n_repos:,} test repositories in 10 folds, identical in both runs",
              f"- recomputation check against the validator's SR/P/R files: "
              f"{checked - mismatches}/{checked} fold values agree to 1e-9", "",
              "| metric | CF-only | hybrid, matched | Δ | p (10 folds) | p (repos) | hybrid, own |",
              "|---|---|---|---|---|---|---|"]
    for m in METRICS:
        for n in NS:
            c, h, o = fold["cf"][m][n], fold["hm"][m][n], fold["ho"][m][n]
            delta = statistics.mean(h) - statistics.mean(c)
            lines.append(f"| {m}@{n} | {fmt(c)} | {fmt(h)} | {delta:+.4f} | "
                         f"{wil([x - y for x, y in zip(h, c)])} | {wil(repo_vals[m][n])} | "
                         f"{fmt(o)} |")
    lines.append("")
    headline.append((label, n_repos, {m: (statistics.mean(fold['cf'][m][10]),
                                         statistics.mean(fold['hm'][m][10]),
                                         statistics.mean(fold['ho'][m][10]))
                                     for m in METRICS}))

# Scale summary, placed before the per-pair sections.
summary = ["## Across corpus sizes, at N = 10", "",
           "| corpus | test repos | " + " | ".join(
               f"{m}@10 CF-only | {m}@10 hybrid matched | {m}@10 hybrid own" for m in METRICS) + " |",
           "|---|---|" + "---|" * (3 * len(METRICS))]
for label, n, h in headline:
    summary.append(f"| {label} | {n:,} | " + " | ".join(
        f"{h[m][0]:.4f} | {h[m][1]:.4f} | {h[m][2]:.4f}" for m in METRICS) + " |")
summary.append("")

if example_done:
    label, k, r, visible, gt_half, cf10, hy10, hm10, s = ex
    strip = lambda xs: ", ".join(x.replace("#DEP#", "") for x in xs)
    mark = lambda xs: ", ".join((f"**{x.replace('#DEP#', '')}**" if x in set(gt_half) else
                                 x.replace("#DEP#", "")) for x in xs)
    summary += ["## Worked example (the first test repository of the first pair)", "",
                f"`{r.replace('___', '/')}`, {label} fold {k}. Hits against the held-back half in bold.",
                "",
                f"- CF-only sees: {strip(visible)}",
                f"- held-back half (the target in the matched view): {strip(gt_half)}",
                f"- CF-only top 10: {mark(cf10)}",
                f"- hybrid top 10: {mark(hy10)}",
                f"- hybrid top 10 with the visible half removed: {mark(hm10)}",
                f"- R@10: CF-only {s['cf']['R'][10]:.3f}, hybrid matched {s['hm']['R'][10]:.3f}; "
                f"hybrid on its own protocol (all {len(visible) + len(gt_half)} topics) "
                f"{s['ho']['R'][10]:.3f}", ""]

head, body = lines[:lines.index("## " + a.pair[0][0])], lines[lines.index("## " + a.pair[0][0]):]
Path(a.out).write_text("\n".join(head + summary + body) + "\n", encoding="utf-8")
print(f"{len(a.pair)} pairs -> {a.out}")
