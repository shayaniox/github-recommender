"""Summarise scripts/bench_kg.sh into OUT/KG_RUNTIME.md.

Two measurements of what the knowledge graph adds to a TopFilter run:

    end-to-end   wall-clock of whole runs A (KG off), B (append), C (rerank), each repetition
                 alone on the machine; median, min and max over the repetitions, and the
                 overhead of B and C against A as the difference of medians
    in-process   cProfile cumulative time of the KG functions in one profiled run per mode:
                 build_adjacency (reads sedkgraph.csv; called once per fold), and the per-test-
                 repository merge step _expand_with_kg (B) or _kg_rerank (C). The profiler
                 slows everything down by a similar factor, so it is the SHARE of the run that
                 carries over, not the absolute seconds.

Usage: python scripts/bench_kg_summary.py OUT
"""

import pstats
import statistics
import sys
from pathlib import Path

OUT = Path(sys.argv[1])
KG_FUNCS = ("build_adjacency", "_expand_with_kg", "_kg_rerank")
NAMES = {"A": "A: KG off", "B": "B: KG append", "C": "C: KG rerank"}

times = {}
for line in (OUT / "timings.tsv").read_text().splitlines():
    rep, run, sec, status, rss = line.split("\t")
    if status != "0":
        sys.exit(f"rep {rep} run {run} exited {status}")
    times.setdefault(run, []).append(float(sec))

med = {r: statistics.median(v) for r, v in times.items()}
lines = ["# Runtime cost of the knowledge graph", "",
         "Generated by `scripts/bench_kg_summary.py` from `scripts/bench_kg.sh`; do not edit by hand.",
         "",
         f"- inputs: `{(OUT / 'inputs.txt').read_text().split()[0]}` with the CNBN seeds "
         f"`{(OUT / 'inputs.txt').read_text().split()[1]}`",
         f"- commit `{(OUT / 'git_sha.txt').read_text().strip()[:7]}`; host: "
         + "; ".join(x.strip() for x in (OUT / 'host.txt').read_text().splitlines()),
         f"- {len(times['A'])} repetitions per mode, one run at a time, A/B/C order rotated "
         "every repetition", "",
         "## End-to-end wall-clock of a TopFilter run (10 folds)", "",
         "| run | median | min | max | overhead vs A (median) |",
         "|---|---|---|---|---|"]
for r in "ABC":
    v = times[r]
    over = "—" if r == "A" else (f"{med[r] - med['A']:+.2f} s "
                                 f"({100 * (med[r] - med['A']) / med['A']:+.1f}%)")
    lines.append(f"| {NAMES[r]} | {med[r]:.2f} s | {min(v):.2f} s | {max(v):.2f} s | {over} |")
spread = max(max(v) - min(v) for v in times.values())
lines += ["", f"Largest min–max spread within one mode: {spread:.2f} s. An overhead smaller "
          "than that cannot be told apart from run-to-run noise in this table; the profile "
          "below measures it directly.", "",
          "## Time inside the KG functions (cProfile, one run per mode)", "",
          "| run | profiled run total | build_adjacency | merge step | KG total | KG share | calls (build / merge) |",
          "|---|---|---|---|---|---|---|"]
for r in "ABC":
    st = pstats.Stats(str(OUT / f"profile_{r}.prof"))
    total = st.total_tt
    cum = {f: 0.0 for f in KG_FUNCS}
    calls = {f: 0 for f in KG_FUNCS}
    for (file, line, func), (cc, nc, tt, ct, callers) in st.stats.items():
        if func in KG_FUNCS:
            cum[func] += ct
            calls[func] += nc
    merge = cum["_expand_with_kg"] + cum["_kg_rerank"]
    merge_calls = calls["_expand_with_kg"] + calls["_kg_rerank"]
    kg = cum["build_adjacency"] + merge
    lines.append(f"| {NAMES[r]} | {total:.2f} s | {cum['build_adjacency']:.3f} s | {merge:.3f} s | "
                 f"{kg:.3f} s | {100 * kg / total:.2f}% | {calls['build_adjacency']} / {merge_calls} |")
lines += ["",
          "build_adjacency runs once per fold (10 per run) and the merge step once per test "
          "repository. Both are independent of the training-set size, while the CF similarity "
          "step grows with N² (fitted N^1.89, `paper_artifacts/RUNTIMES.md`), so the KG share "
          "shrinks as the corpus grows.", ""]
(OUT / "KG_RUNTIME.md").write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines))
